#!/usr/bin/env python3
"""Write figures/Unit_3/3.7_noise_steps.tex: a 16x16 heart, from pure noise to
the finished picture, in four panels. The same idea as the 3.7 widget."""
import math, random, pathlib

HEART = ["................", "................", "...###....###...", "..#####..#####..",
         ".##############.", ".##############.", ".##############.", "..############..",
         "...##########...", "....########....", ".....######.....", "......####......",
         ".......##.......", "................", "................", "................"]
N, S = 16, 0.16                       # cells, cell size in cm
PANELS = [(0, 0.0, "step 0: noise"), (3, 0.2, "step 3"), (6, 0.6, "step 6"), (10, 1.0, "step 10: done")]

rnd = random.Random(7)
noise = [[rnd.gauss(0, 1) for _ in range(N)] for _ in range(N)]
target = [[-1.0 if c == "#" else 1.0 for c in row] for row in HEART]   # -1 black, +1 white

out = [r"\documentclass[border=6pt]{standalone}", r"\input{../preamble}", r"\begin{document}",
       r"\begin{tikzpicture}", "% Generated by scripts/make-noise-steps.py. Do not edit by hand."]
for k, (step, sig, label) in enumerate(PANELS):
    x0 = k * (N * S + 1.1)
    a, b = math.sqrt(sig), math.sqrt(1 - sig)
    for y in range(N):
        for x in range(N):
            v = max(-1.0, min(1.0, a * target[y][x] + b * noise[y][x]))
            black = round((1 - v) / 2 * 100)
            out.append(rf"\fill[black!{black}] ({x0 + x * S:.2f},{-(y + 1) * S:.2f}) rectangle ++({S},{S});")
    out.append(rf"\draw[ink, line width=0.8pt] ({x0},0) rectangle ({x0 + N * S:.2f},{-N * S:.2f});")
    out.append(rf"\node[font=\small\bfseries, text=ink] at ({x0 + N * S / 2:.2f},{-N * S - 0.35:.2f}) {{{label}}};")
    if k:
        out.append(rf"\draw[flow] ({x0 - 0.95:.2f},{-N * S / 2:.2f}) -- ({x0 - 0.15:.2f},{-N * S / 2:.2f});")
out.append(rf"\node[machinebox, font=\small, anchor=south west] at (0,0.25) {{words: ``a heart''}};")
out += [r"\end{tikzpicture}", r"\end{document}", ""]
pathlib.Path("figures/Unit_3/3.7_noise_steps.tex").write_text("\n".join(out))
print("figures/Unit_3/3.7_noise_steps.tex")
